-- 030: Grupos B y C - acciones, bonos, órdenes, transacciones y movimientos de efectivo.
-- Las llaves circulares (ordenes_bono -> lotes_bono / movimientos_efectivo) se cierran con ALTER TABLE al final.
-- Cada tabla marca con "DESVIACIÓN" lo que difiere del modelo E-R del documento (ver docs/REPORTE_CAMBIOS_BASE_DE_DATOS.md).
SET search_path TO datil, public;

-- ---------------------------------------------------------------- acciones
CREATE TABLE acciones_catalogo (
    simbolo             VARCHAR(20) PRIMARY KEY,
    nombre              VARCHAR(120) NOT NULL,
    bolsa               VARCHAR(30),
    moneda              CHAR(3) NOT NULL,
    activa              BOOLEAN NOT NULL DEFAULT TRUE,
    serie_id            INTEGER UNIQUE REFERENCES series_mercado(id) ON DELETE SET NULL,
    riesgo_puntaje      NUMERIC(5,2) CHECK (riesgo_puntaje BETWEEN 0 AND 100),
    riesgo_nivel        VARCHAR(10) CHECK (riesgo_nivel IN ('bajo','medio','alto')),
    riesgo_calculado_en TIMESTAMPTZ,
    riesgo_detalle      JSONB
);
COMMENT ON TABLE acciones_catalogo IS 'El backend acepta cualquier símbolo de Yahoo: la fila se crea al primer uso (compra, alerta o sugerencia).';

CREATE TABLE posiciones_accion (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INTEGER NOT NULL REFERENCES usuarios(id),
    simbolo        VARCHAR(20) NOT NULL REFERENCES acciones_catalogo(simbolo),
    cantidad       NUMERIC(18,6) NOT NULL CHECK (cantidad > 0),
    costo_promedio NUMERIC(18,6) NOT NULL,
    costo_base_mxn NUMERIC(18,2) NOT NULL,
    costo_estimado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_posicion UNIQUE (usuario_id, simbolo)
);

-- ---------------------------------------------------------------- instrumentos de deuda
CREATE TABLE instrumentos (
    simbolo             VARCHAR(20) PRIMARY KEY,
    nombre              VARCHAR(120) NOT NULL,
    tipo                VARCHAR(10) NOT NULL CHECK (tipo IN ('cetes','bono_m','udibono','bonde_d','bonde_f','bpa')),
    tipo_tasa           VARCHAR(10) NOT NULL CHECK (tipo_tasa IN ('cero','fija','real','variable')),
    valor_nominal       NUMERIC(12,2) NOT NULL CHECK (valor_nominal > 0),
    moneda_base         CHAR(3) NOT NULL DEFAULT 'MXN' CHECK (moneda_base IN ('MXN','UDI')),
    plazo_dias          INTEGER NOT NULL CHECK (plazo_dias > 0),
    dias_cupon          INTEGER CHECK (dias_cupon > 0),
    serie_subasta_id    INTEGER REFERENCES series_mercado(id),
    serie_referencia_id INTEGER REFERENCES series_mercado(id),
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_instr_cupon CHECK ((tipo_tasa = 'cero') = (dias_cupon IS NULL)),
    CONSTRAINT ck_instr_udi   CHECK ((moneda_base = 'UDI') = (tipo = 'udibono')),
    CONSTRAINT ck_instr_var   CHECK ((tipo_tasa = 'variable') = (serie_referencia_id IS NOT NULL))
);

CREATE TABLE emisiones (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrumento_id    VARCHAR(20) NOT NULL REFERENCES instrumentos(simbolo),
    clave             VARCHAR(40) NOT NULL,   -- DESVIACIÓN: VARCHAR(40); el backend genera claves SIMBOLO-AAAAMMDD
    fecha_emision     DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    tasa_cupon        NUMERIC(10,6),           -- DESVIACIÓN: (10,6) en vez de (8,4)
    CONSTRAINT ck_emision_fechas CHECK (fecha_vencimiento > fecha_emision),
    CONSTRAINT uq_emision_clave UNIQUE NULLS NOT DISTINCT (clave, tasa_cupon)
);

CREATE TABLE subastas (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrumento_id    VARCHAR(20) NOT NULL REFERENCES instrumentos(simbolo),
    emision_id        INTEGER REFERENCES emisiones(id),
    fecha_subasta     DATE NOT NULL,
    fecha_colocacion  DATE NOT NULL,
    plazo_dias_reales INTEGER NOT NULL CHECK (plazo_dias_reales > 0),
    realizada         BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_subasta UNIQUE (instrumento_id, fecha_colocacion),
    CONSTRAINT ck_subasta_fechas   CHECK (fecha_colocacion > fecha_subasta),
    CONSTRAINT ck_subasta_realizada CHECK (NOT realizada OR emision_id IS NOT NULL)
);

-- ---------------------------------------------------------------- órdenes y lotes de bonos
CREATE TABLE ordenes_bono (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                  UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,  -- DESVIACIÓN: id público (la API usa UUID)
    usuario_id           INTEGER NOT NULL REFERENCES usuarios(id),
    subasta_id           INTEGER NOT NULL REFERENCES subastas(id),
    origen               VARCHAR(25) NOT NULL DEFAULT 'compra'
                         CHECK (origen IN ('compra','reinversion_vencimiento','reinversion_cupon')),
    monto_mxn            NUMERIC(18,2) NOT NULL CHECK (monto_mxn > 0),
    reinversion_modo     VARCHAR(10) NOT NULL DEFAULT 'ninguna'
                         CHECK (reinversion_modo IN ('ninguna','todo','capital','monto','porcentaje')),
    reinversion_valor    NUMERIC(18,2),
    lote_origen_id       INTEGER,   -- FK al final (ciclo)
    movimiento_origen_id INTEGER,   -- FK al final (ciclo)
    estado               VARCHAR(10) NOT NULL DEFAULT 'pendiente'
                         CHECK (estado IN ('pendiente','ejecutada','cancelada','fallida')),
    motivo_fallo         VARCHAR(150),
    creada_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    ejecutada_en         TIMESTAMPTZ,
    cancelada_en         TIMESTAMPTZ,
    CONSTRAINT ck_orden_valor   CHECK ((reinversion_modo IN ('monto','porcentaje')) = (reinversion_valor IS NOT NULL)),
    CONSTRAINT ck_orden_pct     CHECK (reinversion_modo <> 'porcentaje' OR reinversion_valor BETWEEN 0.01 AND 100),
    CONSTRAINT ck_orden_vence   CHECK ((origen = 'reinversion_vencimiento') = (lote_origen_id IS NOT NULL)),
    CONSTRAINT ck_orden_cupon   CHECK ((origen = 'reinversion_cupon') = (movimiento_origen_id IS NOT NULL)),
    CONSTRAINT ck_orden_ejec    CHECK ((estado = 'ejecutada') = (ejecutada_en IS NOT NULL)),
    CONSTRAINT ck_orden_cancel  CHECK ((estado = 'cancelada') = (cancelada_en IS NOT NULL))
);
CREATE INDEX ix_ordenes_pendientes ON ordenes_bono (subasta_id) WHERE estado = 'pendiente';
CREATE INDEX ix_ordenes_usuario ON ordenes_bono (usuario_id, creada_en DESC);
-- Antiduplicado: un lote que vence genera una sola reinversión viva; un cupón también.
CREATE UNIQUE INDEX uq_orden_reinv_lote  ON ordenes_bono (lote_origen_id)
    WHERE origen = 'reinversion_vencimiento' AND estado IN ('pendiente','ejecutada');
CREATE UNIQUE INDEX uq_orden_reinv_cupon ON ordenes_bono (movimiento_origen_id)
    WHERE origen = 'reinversion_cupon';

CREATE TABLE lotes_bono (
    id                          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                         UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,  -- DESVIACIÓN: lot_id público
    usuario_id                  INTEGER NOT NULL REFERENCES usuarios(id),
    emision_id                  INTEGER NOT NULL REFERENCES emisiones(id),
    orden_id                    INTEGER UNIQUE REFERENCES ordenes_bono(id),
    cantidad                    NUMERIC(18,6) NOT NULL CHECK (cantidad >= 0),
    fecha_compra                DATE NOT NULL,
    precio_compra               NUMERIC(18,7) NOT NULL,
    intereses_devengados_compra NUMERIC(24,12) NOT NULL DEFAULT 0,
    valor_udi_compra            NUMERIC(12,6),
    tasa_compra                 NUMERIC(10,6) NOT NULL,   -- DESVIACIÓN: (10,6) en vez de (8,4)
    reinversion_modo            VARCHAR(10) NOT NULL DEFAULT 'ninguna'
                                CHECK (reinversion_modo IN ('ninguna','todo','capital','monto','porcentaje')),
    reinversion_valor           NUMERIC(18,2),
    proximo_cupon               DATE,
    cupones_pagados             INTEGER NOT NULL DEFAULT 0 CHECK (cupones_pagados >= 0), -- DESVIACIÓN: el backend cuenta cupones
    estado                      VARCHAR(10) NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente','vencido','vendido')),
    CONSTRAINT ck_lote_valor CHECK ((reinversion_modo IN ('monto','porcentaje')) = (reinversion_valor IS NOT NULL)),
    CONSTRAINT ck_lote_pct   CHECK (reinversion_modo <> 'porcentaje' OR reinversion_valor BETWEEN 0.01 AND 100)
);
CREATE INDEX ix_lotes_vigentes ON lotes_bono (usuario_id) WHERE estado = 'vigente';
CREATE INDEX ix_lotes_usuario ON lotes_bono (usuario_id);

ALTER TABLE ordenes_bono ADD CONSTRAINT fk_orden_lote_origen FOREIGN KEY (lote_origen_id) REFERENCES lotes_bono(id);

-- ---------------------------------------------------------------- transacciones y movimientos
CREATE TABLE transacciones (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                    UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público
    usuario_id             INTEGER NOT NULL REFERENCES usuarios(id),
    fecha_hora             TIMESTAMPTZ NOT NULL,
    tipo_activo            VARCHAR(10) NOT NULL CHECK (tipo_activo IN ('accion','bono')),
    lado                   VARCHAR(10) NOT NULL CHECK (lado IN ('compra','venta')),
    simbolo_accion         VARCHAR(20) REFERENCES acciones_catalogo(simbolo),
    lote_id                INTEGER REFERENCES lotes_bono(id),
    cantidad               NUMERIC(18,6) NOT NULL CHECK (cantidad > 0),
    precio                 NUMERIC(18,7) NOT NULL,
    moneda                 CHAR(3) NOT NULL DEFAULT 'MXN',
    tipo_cambio            NUMERIC(18,8) NOT NULL DEFAULT 1,   -- DESVIACIÓN: (18,8); monedas chicas (KRW, JPY) necesitan 8 decimales
    tasa                   NUMERIC(10,6),                      -- DESVIACIÓN: (10,6)
    total_mxn              NUMERIC(18,2) NOT NULL CHECK (total_mxn > 0),
    utilidad_realizada_mxn NUMERIC(18,2),
    hecha_por              INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    rol_de_quien_la_hizo   VARCHAR(10) NOT NULL CHECK (rol_de_quien_la_hizo IN ('admin','consultor','usuario','sistema')),
    origen                 VARCHAR(16) NOT NULL
                           CHECK (origen IN ('cliente','admin','automatico','orden_programada')), -- DESVIACIÓN: + orden_programada
    orden_id               INTEGER REFERENCES ordenes_bono(id),
    CONSTRAINT ck_tx_activo CHECK (
        (tipo_activo = 'accion' AND simbolo_accion IS NOT NULL AND lote_id IS NULL) OR
        (tipo_activo = 'bono'   AND lote_id IS NOT NULL AND simbolo_accion IS NULL))
);
CREATE INDEX ix_transacciones_usuario_fecha ON transacciones (usuario_id, fecha_hora DESC);
CREATE UNIQUE INDEX uq_tx_orden_compra ON transacciones (orden_id) WHERE orden_id IS NOT NULL AND lado = 'compra';

CREATE TABLE movimientos_efectivo (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid                    UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público (cupones/vencimientos)
    usuario_id             INTEGER NOT NULL REFERENCES usuarios(id),
    fecha_hora             TIMESTAMPTZ NOT NULL,
    tipo                   VARCHAR(12) NOT NULL CHECK (tipo IN ('deposito','retiro','compra','venta','cupon','vencimiento')),
    monto_mxn              NUMERIC(18,2) NOT NULL CHECK (monto_mxn <> 0),
    transaccion_id         INTEGER UNIQUE REFERENCES transacciones(id),
    lote_id                INTEGER REFERENCES lotes_bono(id),
    hecho_por              INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    nota                   TEXT,
    cantidad               NUMERIC(18,6),   -- DESVIACIÓN: foto de cupón/vencimiento (títulos al momento del pago)
    tasa                   NUMERIC(10,6),   -- DESVIACIÓN
    utilidad_realizada_mxn NUMERIC(18,2),   -- DESVIACIÓN: utilidad al vencimiento
    CONSTRAINT ck_mov_signo CHECK ((tipo IN ('deposito','venta','cupon','vencimiento')) = (monto_mxn > 0)),
    CONSTRAINT ck_mov_tx    CHECK ((tipo IN ('compra','venta')) = (transaccion_id IS NOT NULL)),
    CONSTRAINT ck_mov_lote  CHECK ((tipo IN ('cupon','vencimiento')) = (lote_id IS NOT NULL))
);
CREATE INDEX ix_movimientos_usuario_fecha ON movimientos_efectivo (usuario_id, fecha_hora DESC);
-- Antiduplicado: un cupón por lote y fecha de pago; un solo vencimiento por lote.
CREATE UNIQUE INDEX uq_mov_cupon_lote_fecha ON movimientos_efectivo (lote_id, fecha_hora) WHERE tipo = 'cupon';
CREATE UNIQUE INDEX uq_mov_vencimiento_lote ON movimientos_efectivo (lote_id) WHERE tipo = 'vencimiento';

ALTER TABLE ordenes_bono ADD CONSTRAINT fk_orden_mov_origen FOREIGN KEY (movimiento_origen_id) REFERENCES movimientos_efectivo(id);
