-- 020: Grupo D - Datos de mercado (series, historia diaria, calendario inhábil).
SET search_path TO datil, public;

CREATE TABLE series_mercado (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente         VARCHAR(10)  NOT NULL CHECK (fuente IN ('banxico','yahoo')),
    codigo         VARCHAR(30)  NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    frecuencia     VARCHAR(10)  NOT NULL CHECK (frecuencia IN ('minuto','diaria','semanal')),
    moneda         CHAR(3),
    ultimo_valor   NUMERIC(18,7),
    ultimo_momento TIMESTAMPTZ,
    actualizada_en TIMESTAMPTZ,
    CONSTRAINT uq_series_fuente_codigo UNIQUE (fuente, codigo)
);

CREATE TABLE datos_mercado (
    serie_id INTEGER NOT NULL REFERENCES series_mercado(id) ON DELETE CASCADE,
    fecha    DATE NOT NULL,
    valor    NUMERIC(18,7) NOT NULL,
    PRIMARY KEY (serie_id, fecha)
);

CREATE TABLE dias_inhabiles (
    fecha       DATE PRIMARY KEY,
    descripcion VARCHAR(100)
);
