SET search_path TO datil, public;

CREATE TABLE historial_patrimonio (
    usuario_id                       INTEGER NOT NULL REFERENCES usuarios(id),
    fecha                            DATE NOT NULL,
    patrimonio_mxn                   NUMERIC(18,2) NOT NULL,
    efectivo_mxn                     NUMERIC(18,2) NOT NULL,
    invertido_mxn                    NUMERIC(18,2) NOT NULL,
    ganancia_sin_vender_mxn          NUMERIC(18,2),
    ganancia_realizada_acumulada_mxn NUMERIC(18,2),
    riesgo_puntaje                   NUMERIC(5,2) CHECK (riesgo_puntaje BETWEEN 0 AND 100),
    riesgo_nivel                     VARCHAR(10) CHECK (riesgo_nivel IN ('bajo','medio','alto')),
    riesgo_detalle                   JSONB,
    PRIMARY KEY (usuario_id, fecha)
);

CREATE TABLE sugerencias (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id            INTEGER NOT NULL REFERENCES usuarios(id),
    clave                 VARCHAR(50) NOT NULL,
    simbolo               VARCHAR(20) REFERENCES acciones_catalogo(simbolo),
    severidad             VARCHAR(10) NOT NULL CHECK (severidad IN ('alta','media','baja')),
    titulo                VARCHAR(150) NOT NULL,
    detalle               TEXT NOT NULL,
    vista_por_primera_vez TIMESTAMPTZ NOT NULL,
    resuelta_en           TIMESTAMPTZ,
    CONSTRAINT ck_sug_resuelta CHECK (resuelta_en IS NULL OR resuelta_en >= vista_por_primera_vez)
);
CREATE UNIQUE INDEX uq_sugerencia_abierta ON sugerencias (cliente_id, clave, COALESCE(simbolo, ''))
    WHERE resuelta_en IS NULL;

CREATE TABLE alertas (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid          UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público
    cliente_id   INTEGER NOT NULL REFERENCES usuarios(id),
    creada_por   INTEGER NOT NULL REFERENCES usuarios(id),
    rol_creador  VARCHAR(10) NOT NULL CHECK (rol_creador IN ('usuario','consultor','admin')),
    simbolo      VARCHAR(20) NOT NULL,      -- '*' = todo el portafolio, por eso sin FK
    tipo         VARCHAR(10) NOT NULL CHECK (tipo IN ('perdida','ganancia')),
    porcentaje   NUMERIC(6,2) NOT NULL CHECK (porcentaje > 0),
    indicacion   VARCHAR(10) NOT NULL DEFAULT 'aviso' CHECK (indicacion IN ('aviso','vender','comprar')),
    nivel        SMALLINT NOT NULL DEFAULT 0 CHECK (nivel BETWEEN 0 AND 3),
    nivel_desde  TIMESTAMPTZ,
    activa       BOOLEAN NOT NULL DEFAULT TRUE,
    creada_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_alertas_cliente ON alertas (cliente_id) WHERE activa;

CREATE TABLE eventos_alerta (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id      INTEGER NOT NULL REFERENCES alertas(id),
    fecha_hora     TIMESTAMPTZ NOT NULL DEFAULT now(),
    nivel_anterior SMALLINT NOT NULL CHECK (nivel_anterior BETWEEN 0 AND 3),
    nivel_nuevo    SMALLINT NOT NULL CHECK (nivel_nuevo BETWEEN 0 AND 3),
    movimiento_pct NUMERIC(6,2),
    CONSTRAINT ck_evento_cambio CHECK (nivel_anterior <> nivel_nuevo)
);
CREATE INDEX ix_eventos_alerta ON eventos_alerta (alerta_id, fecha_hora DESC);

CREATE TABLE avisos (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid              UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público
    cliente_id       INTEGER NOT NULL REFERENCES usuarios(id),
    de_usuario_id    INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    tipo             VARCHAR(10) NOT NULL CHECK (tipo IN ('aviso','riesgo','accion','alerta')),
    titulo           VARCHAR(150) NOT NULL,
    mensaje          TEXT NOT NULL,
    fecha_hora       TIMESTAMPTZ NOT NULL DEFAULT now(),
    leido            BOOLEAN NOT NULL DEFAULT FALSE,
    leido_en         TIMESTAMPTZ,
    sugerencia_id    INTEGER REFERENCES sugerencias(id) ON DELETE SET NULL,
    evento_alerta_id INTEGER REFERENCES eventos_alerta(id) ON DELETE SET NULL,
    CONSTRAINT ck_aviso_leido CHECK (leido = (leido_en IS NOT NULL))
);
CREATE INDEX ix_avisos_cliente ON avisos (cliente_id, fecha_hora DESC);

CREATE TABLE metas (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid            UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público
    cliente_id     INTEGER NOT NULL REFERENCES usuarios(id),
    titulo         VARCHAR(150) NOT NULL,
    monto_objetivo NUMERIC(18,2) NOT NULL CHECK (monto_objetivo > 0),
    fecha_objetivo DATE,
    estado         VARCHAR(10) NOT NULL DEFAULT 'en curso' CHECK (estado IN ('en curso','lograda','cancelada')),
    creada_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    lograda_en     TIMESTAMPTZ
);
CREATE INDEX ix_metas_cliente ON metas (cliente_id);

CREATE TABLE notas (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid        UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,   -- DESVIACIÓN: id público
    cliente_id INTEGER NOT NULL REFERENCES usuarios(id),
    autor_id   INTEGER NOT NULL REFERENCES usuarios(id),
    privada    BOOLEAN NOT NULL DEFAULT FALSE,
    texto      TEXT NOT NULL,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_notas_cliente ON notas (cliente_id, autor_id);

CREATE TABLE preferencias_alerta (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
    canal      VARCHAR(10) NOT NULL CHECK (canal IN ('web','correo','sms','whatsapp','push','telegram')),
    frecuencia VARCHAR(10) NOT NULL DEFAULT 'inmediata' CHECK (frecuencia IN ('inmediata','diaria','semanal')),
    activa     BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (usuario_id, canal)
);

CREATE TABLE envios_aviso (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aviso_id         INTEGER REFERENCES avisos(id),
    evento_alerta_id INTEGER REFERENCES eventos_alerta(id),
    canal            VARCHAR(10) NOT NULL CHECK (canal IN ('web','correo','sms','whatsapp','push','telegram')),
    estado           VARCHAR(10) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','enviado','fallido')),
    enviado_en       TIMESTAMPTZ,
    error            TEXT,
    CONSTRAINT ck_envio_origen CHECK (aviso_id IS NOT NULL OR evento_alerta_id IS NOT NULL)
);

CREATE TABLE auditoria_general (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora  TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario_id  INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    cliente_id  INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    accion      VARCHAR(50) NOT NULL,
    objeto_tipo VARCHAR(50) NOT NULL,
    objeto_id   VARCHAR(50),
    antes       JSONB,
    despues     JSONB,
    ip          VARCHAR(45),
    resultado   VARCHAR(10) NOT NULL DEFAULT 'exito' CHECK (resultado IN ('exito','error')),
    motivo      TEXT
);
CREATE INDEX ix_auditoria_fecha ON auditoria_general (fecha_hora DESC);
CREATE INDEX ix_auditoria_cliente ON auditoria_general (cliente_id, fecha_hora DESC);
