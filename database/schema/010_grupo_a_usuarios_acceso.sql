-- 010: Grupo A - Usuarios y acceso (puestos, usuarios, asignaciones, sesiones, intentos de login).
SET search_path TO datil, public;

CREATE TABLE puestos (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT,
    permisos    TEXT[] NOT NULL DEFAULT '{}'
);
COMMENT ON TABLE puestos IS 'Catálogo de puestos; cada puesto agrupa permisos (módulo o módulo.sección).';

CREATE TABLE usuarios (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario                   VARCHAR(50)  NOT NULL UNIQUE,
    nombre                    VARCHAR(120) NOT NULL,
    correo                    VARCHAR(150) UNIQUE,
    telefono                  VARCHAR(20),
    contrasena_hash           VARCHAR(255) NOT NULL,
    rol                       VARCHAR(20)  NOT NULL CHECK (rol IN ('admin','consultor','usuario')),
    puesto_id                 INTEGER REFERENCES puestos(id) ON DELETE RESTRICT,
    permisos                  TEXT[] NOT NULL DEFAULT '{}',
    estado                    VARCHAR(20)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','suspendido','baja')),
    baja_en                   TIMESTAMPTZ,
    efectivo_mxn              NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (efectivo_mxn >= 0),
    debe_cambiar_contrasena   BOOLEAN NOT NULL DEFAULT FALSE,
    contrasena_cambiada_en    TIMESTAMPTZ,
    dos_pasos_metodo          VARCHAR(10) CHECK (dos_pasos_metodo IN ('totp','correo')),
    dos_pasos_secreto_cifrado TEXT,
    dos_pasos_activo          BOOLEAN NOT NULL DEFAULT FALSE,
    recuperacion_token_hash   VARCHAR(255),
    recuperacion_expira_en    TIMESTAMPTZ,
    creado_en                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    creado_por                INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT ck_usuarios_baja     CHECK ((estado = 'baja') = (baja_en IS NOT NULL)),
    CONSTRAINT ck_usuarios_efectivo CHECK (rol = 'usuario' OR efectivo_mxn = 0)
);
COMMENT ON COLUMN usuarios.efectivo_mxn IS 'Saldo en pesos. Solo lo modifica el trigger de movimientos_efectivo (saldo = suma de movimientos).';
CREATE INDEX ix_usuarios_permisos ON usuarios USING GIN (permisos);
CREATE INDEX ix_usuarios_rol ON usuarios (rol);

CREATE TABLE asignaciones_consultor (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   INTEGER NOT NULL REFERENCES usuarios(id),
    consultor_id INTEGER NOT NULL REFERENCES usuarios(id),
    desde        DATE NOT NULL,
    hasta        DATE,
    asignado_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT ck_asig_distintos CHECK (cliente_id <> consultor_id),
    CONSTRAINT ck_asig_fechas    CHECK (hasta IS NULL OR hasta >= desde)
);
CREATE UNIQUE INDEX uq_asignacion_vigente ON asignaciones_consultor (cliente_id) WHERE hasta IS NULL;
CREATE INDEX ix_asignaciones_consultor ON asignaciones_consultor (consultor_id) WHERE hasta IS NULL;

CREATE TABLE sesiones (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti              UUID NOT NULL UNIQUE,
    usuario_id       INTEGER NOT NULL REFERENCES usuarios(id),
    iniciada_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultima_actividad TIMESTAMPTZ NOT NULL DEFAULT now(),
    cerrada_en       TIMESTAMPTZ,
    ip               VARCHAR(45) NOT NULL,
    dispositivo      VARCHAR(150)
);
CREATE INDEX ix_sesiones_usuario_ip ON sesiones (usuario_id, ip);

CREATE TABLE intentos_login (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_escrito VARCHAR(50),
    usuario_id      INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    fecha_hora      TIMESTAMPTZ NOT NULL DEFAULT now(),
    exitoso         BOOLEAN NOT NULL,
    ip              VARCHAR(45) NOT NULL,
    motivo_fallo    VARCHAR(100)
);
CREATE INDEX ix_intentos_usuario_fecha ON intentos_login (usuario_escrito, fecha_hora DESC);
